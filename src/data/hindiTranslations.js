export function getLocalHindiTranslation(text) {
  const normalizedText = text?.trim()

  if (!normalizedText) {
    return text
  }

  if (hindiTranslations[normalizedText]) {
    return hindiTranslations[normalizedText]
  }

  const prefixMatch = Object.keys(hindiTranslations).find(
    (phrase) => phrase.endsWith(':') && normalizedText.startsWith(`${phrase} `),
  )

  if (prefixMatch) {
    const suffix = normalizedText.slice(prefixMatch.length).trim()
    const translatedSuffix = suffix ? getLocalHindiTranslation(suffix) || suffix : ''

    return `${hindiTranslations[prefixMatch]}${translatedSuffix ? ` ${translatedSuffix}` : ''}`
  }

  const questionMatch = normalizedText.match(/^Question (\d+) of (\d+)$/)

  if (questionMatch) {
    return `प्रश्न ${questionMatch[1]} में से ${questionMatch[2]}`
  }

  const completedLessonsMatch = normalizedText.match(/^(\d+) of (\d+) lessons completed$/)

  if (completedLessonsMatch) {
    return `${completedLessonsMatch[1]} में से ${completedLessonsMatch[2]} पाठ पूरे`
  }

  const courseCountMatch = normalizedText.match(/^(\d+) courses? shown$/)

  if (courseCountMatch) {
    return `${courseCountMatch[1]} कोर्स दिखाए गए`
  }

  const quizCountMatch = normalizedText.match(/^(\d+) quizzes$/)

  if (quizCountMatch) {
    return `${quizCountMatch[1]} क्विज`
  }

  const questionCountMatch = normalizedText.match(/^(\d+) questions$/)

  if (questionCountMatch) {
    return `${questionCountMatch[1]} प्रश्न`
  }

  const percentCorrectMatch = normalizedText.match(/^(\d+)% correct$/)

  if (percentCorrectMatch) {
    return `${percentCorrectMatch[1]}% सही`
  }

  return ''
}
